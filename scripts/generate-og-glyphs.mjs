import { readFile, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import sharp from 'sharp';

const fontPath = process.argv[2];
if (!fontPath) {
  throw new Error('Pass the path to a Korean OTF/TTF font, for example: npm run generate:og-glyphs -- /path/to/Pretendard-Bold.otf');
}

const font = (await readFile(resolve(fontPath))).toString('base64');
const genres = JSON.parse(await readFile(new URL('../src/data/genres.json', import.meta.url), 'utf8'));
const fixedLabels = [
  '나의 음악 성격', '장르 유사도', '너는 어떤 음악 타입?',
  '친구가 초대했어요', '음악 취향 비교', '우리 음악 궁합',
  '거의 같은 플레이리스트', '같이 들을수록 좋은 사이',
  '닮음과 새로움의 균형', '서로 다른 취향의 발견',
];
const source = [...genres.flatMap(genre => [genre.nameKo, genre.personalityAnalysis?.typeTitle]), ...fixedLabels].join('');
const characters = [...new Set(source.match(/[가-힣]/g) || [])].sort();
const glyphs = {};

for (const character of characters) {
  const svg = `<svg width="32" height="32" xmlns="http://www.w3.org/2000/svg"><style>@font-face{font-family:OgKorean;src:url(data:font/otf;base64,${font})}</style><text x="0" y="27" font-family="OgKorean" font-size="27" font-weight="700" fill="white">${character}</text></svg>`;
  const { data, info } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const rows = [];
  for (let y = 0; y < 32; y += 1) {
    let bits = 0;
    for (let x = 0; x < 32; x += 1) {
      bits = (bits << 1) | (data[(y * 32 + x) * info.channels + 3] >= 96 ? 1 : 0);
    }
    rows.push((bits >>> 0).toString(16).padStart(8, '0'));
  }
  glyphs[character] = rows.join('');
}

const generated = `// Generated by scripts/generate-og-glyphs.mjs from ${basename(fontPath)}.\n// Keep this file committed so Cloudflare Workers need no font engine.\nexport const KOREAN_GLYPHS: Record<string, string> = ${JSON.stringify(glyphs, null, 2)};\n`;
await writeFile(new URL('../cloudflare/koreanGlyphs.ts', import.meta.url), generated);
console.log(`Generated ${characters.length} Korean glyphs`);
