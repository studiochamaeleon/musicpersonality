import { readFile, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import sharp from 'sharp';

const fontPath = process.argv[2];
if (!fontPath) throw new Error('Pass the path to a Japanese TTC/OTF font.');

const font = (await readFile(resolve(fontPath))).toString('base64');
const translationSource = await readFile(new URL('../src/lib/genreTranslationsJa.ts', import.meta.url), 'utf8');
const fixedLabels = [
  '私の音楽性格', 'ジャンル一致度', 'あなたの音楽タイプは',
  '友達からの招待', '音楽の好みを比較', '二人の音楽相性',
  'ほぼ同じプレイリスト', '一緒に聴くほど好相性',
  '似ている音と新しい音', '違う好みから発見',
].join('');
const source = `${translationSource}${fixedLabels}`;
const characters = [...new Set(source.match(/[぀-ヿ㐀-鿿々ー・]/g) || [])].sort();
const glyphs = {};

for (const character of characters) {
  const svg = `<svg width="32" height="32" xmlns="http://www.w3.org/2000/svg"><style>@font-face{font-family:OgJapanese;src:url(data:font/ttf;base64,${font})}</style><text x="0" y="27" font-family="OgJapanese" font-size="27" font-weight="700" fill="white">${character}</text></svg>`;
  const { data, info } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const rows = [];
  for (let y = 0; y < 32; y += 1) {
    let bits = 0;
    for (let x = 0; x < 32; x += 1) bits = (bits << 1) | (data[(y * 32 + x) * info.channels + 3] >= 96 ? 1 : 0);
    rows.push((bits >>> 0).toString(16).padStart(8, '0'));
  }
  glyphs[character] = rows.join('');
}

const generated = `// Generated by scripts/generate-ja-og-glyphs.mjs from ${basename(fontPath)}.\n// Keep this file committed so Cloudflare Workers need no font engine.\nexport const JAPANESE_GLYPHS: Record<string, string> = ${JSON.stringify(glyphs, null, 2)};\n`;
await writeFile(new URL('../cloudflare/japaneseGlyphs.ts', import.meta.url), generated);
console.log(`Generated ${characters.length} Japanese glyphs`);
